const WIDTH = PIXELS[0].length;
const HEIGHT = PIXELS.length;

/** An SVG path covering every pixel marked `mark`, one rectangle per horizontal run. */
function pathOf(mark: string) {
  let d = "";
  PIXELS.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== mark) continue;
      const start = x;
      while (row[x + 1] === mark) x++;
      d += `M${start} ${y}h${x - start + 1}v1h${-(x - start + 1)}z`;
    }
  });
  return d;
}

const INK = pathOf("#");
const CURL = pathOf("~");

/** The wordmark at 1× (one screen pixel per art pixel), so it stays crisp. */
export function Wordmark() {
  return (
    <svg className="brand-logo" viewBox={`0 0 ${WIDTH} ${HEIGHT}`} width={WIDTH} height={HEIGHT} shapeRendering="crispEdges" role="img" aria-label="Koihongo">
      <path d={INK} fill="var(--wordmark-ink)" />
      <path d={CURL} fill="var(--wordmark-curl)" />
    </svg>
  );
}
